"""Generate soh/src/code/ml_entrance_map.c: ML entrance number <-> SoH entrance index.

ML keeps vanilla's entrance *numbers* in engine code (dungeon return on load, game-over continue, ...) but reads
them through its own entrance table, where 370 of them mean a different place. Scene exits are remapped in the
data; code that uses literal numbers calls MlEntrance_ToSoh / MlEntrance_FromSoh instead. Same mapping rule as
ml_entrance.remap_exits (exact scene+spawn, else the scene's lowest entrance). Rerun after changing entrances.
"""
from mspaths import PIPE, SOH
import sys
sys.path.insert(0, PIPE)
import ml_entrance as m
OUT = SOH + '/src/code/ml_entrance_map.c'
# ML entrances whose (scene, spawn) has a vanilla entrance but must stay distinguishable from it. 0x420 is the
# Fishing Pond again, reached from ML's patched cutscene destination 56 with a cutscene layer; Ml_Fishpond tells
# it apart from 0x41C (same spot) and the layer needs an 8-entry group (entrance_table.h 0x636).
OVERRIDE = {e: 0x636 for e in range(0x420, 0x428)}
to_soh = []
for e, (sc, sp, _) in enumerate(m.ML):
    if e in OVERRIDE:
        to_soh.append(OVERRIDE[e])
        continue
    sc = m.SCENE_TRANSLATE.get(sc, sc)
    v = m.REV.get((sc, sp))
    if v is None:
        same = [i for (s2, _), i in m.REV.items() if s2 == sc]
        v = min(same) if same else e
    to_soh.append(v)
from_soh = {}
for e, v in enumerate(to_soh):
    from_soh.setdefault(v, e)
n_soh = max(max(to_soh), max(m.REV.values())) + 1
rev = [from_soh.get(i, i) for i in range(n_soh)]
def rows(vals):
    return '\n'.join('    ' + ', '.join(f'0x{v:03X}' for v in vals[i:i+12]) + ',' for i in range(0, len(vals), 12))
open(OUT, 'w').write(f'''// GENERATED by MissingShip/pipeline/gen_entrance_map.py -- do not edit by hand.
// MissingShip: translate between ML's entrance numbering and SoH's entrance table (see ml_entrance_map.h).
#include "ml_entrance_map.h"

static const u16 sMlToSoh[{len(to_soh)}] = {{
{rows(to_soh)}
}};

static const u16 sSohToMl[{len(rev)}] = {{
{rows(rev)}
}};

u16 MlEntrance_ToSoh(u16 mlIndex) {{
    return (mlIndex < ARRAY_COUNT(sMlToSoh)) ? sMlToSoh[mlIndex] : mlIndex;
}}

u16 MlEntrance_FromSoh(u16 sohIndex) {{
    return (sohIndex < ARRAY_COUNT(sSohToMl)) ? sSohToMl[sohIndex] : sohIndex;
}}
''')
print(f'wrote {OUT}: {len(to_soh)} ML entrances, {len(rev)} SoH entrances')
