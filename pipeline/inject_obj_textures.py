"""Port the textures (and collision tweaks) ML made inside otherwise-vanilla objects (MS-020).

These ML objects are byte-for-byte the size of their MQ debug counterparts, with the same layout, so SoH's own MQ
XMLs describe them. Texture-only copies of those XMLs are written to xml/objtex/ as ml_<object> (ms_cycle.sh names
the matching ML dma files the same way). ZAPD extracts them from ML's ROM, and only textures whose pixels differ
from stock SoH's ship, under the vanilla paths objects/<object>/<texture>. The game keeps drawing its own
display lists and picks up ML's art. Pure data: drop-in compatible.

The baseline is the MQ debug ROM ML was built from, not stock SoH (which is generated from a retail ROM): a texture
ships only if ML's bytes differ from the debug ROM's (ML redrew it) AND from stock's (otherwise it's a no-op).
Comparing with stock alone would ship debug-vs-retail version differences ML never made (3 in
gameplay_dangeon_keep did).
"""
from mspaths import DEBUG_ROM, ML_ROM, OOT_O2R, PIPE, SOH, ZAPD, ZAPD_CWD, zapd_config
import os, re, struct, subprocess, sys, zipfile
from yaz0 import get_file

# ML dma index of each object (ms_cycle.sh names them ml_<object>); the debug ROM's is found by name
ML_DMA = {'gameplay_dangeon_keep': 351, 'object_box': 358, 'object_bombf': 367, 'object_bdoor': 36,
          'object_haka_door': 395, 'object_jya_obj': 58}
BPP = {'rgba16': 2, 'rgba32': 4, 'i4': 0.5, 'i8': 1, 'ia4': 0.5, 'ia8': 1, 'ia16': 2, 'ci4': 0.5, 'ci8': 1}

def rom_file(path, index):
    rom = open(path, 'rb').read()
    e = struct.unpack('>IIII', rom[0x12F70 + 16 * index: 0x12F70 + 16 * index + 16])
    return get_file(rom, *e)

def ml_changed(obj):
    """Names of the textures in <obj> whose bytes differ between ML and the MQ debug ROM."""
    names = open(os.path.join(SOH, 'assets', 'extractor', 'filelists', 'dbg.txt')).read().split('\n')
    ml, dbg = rom_file(ML_ROM, ML_DMA[obj]), rom_file(DEBUG_ROM, names.index(obj))
    xml = open(os.path.join(XML_SRC, obj + '.xml')).read()
    out = set()
    for m in re.finditer(r'<Texture Name="(\w+)"[^>]*Format="(\w+)"[^>]*Width="(\d+)"[^>]*Height="(\d+)"'
                         r'[^>]*Offset="(0x[0-9A-Fa-f]+)"', xml):
        name, fmt, w, h, off = m.group(1), m.group(2), int(m.group(3)), int(m.group(4)), int(m.group(5), 16)
        size = int(w * h * BPP[fmt])
        if ml[off:off + size] != dbg[off:off + size]:
            out.add(name)
    # Collisions: a header points at the vertices, polygons and surface types it owns (they sit before it), so
    # compare those ranges. Collision resources carry no resource paths, so ML's can ship under vanilla's name.
    for m in re.finditer(r'<Collision Name="(\w+)"[^>]*Offset="(0x[0-9A-Fa-f]+)"', xml):
        name, h = m.group(1), int(m.group(2), 16)
        nv, vp, npoly, pp, sp = struct.unpack('>HxxIHxxII', dbg[h + 12:h + 32])
        vp, pp, sp = vp & 0xFFFFFF, pp & 0xFFFFFF, sp & 0xFFFFFF
        nsurf = 1 + max(struct.unpack('>H', dbg[pp + 16 * i:pp + 16 * i + 2])[0] for i in range(npoly))
        ranges = [(h, 0x2C), (vp, nv * 6), (pp, npoly * 16), (sp, nsurf * 8)]
        if any(ml[o:o + n] != dbg[o:o + n] for o, n in ranges):
            out.add(name)
    return out

OBJECTS = ['gameplay_dangeon_keep', 'object_box', 'object_bombf', 'object_bdoor', 'object_haka_door',
           'object_jya_obj']
XML_SRC = os.path.join(SOH, 'assets', 'xml', 'GC_MQ_PAL_F', 'objects')
XML_DIR = os.path.join(PIPE, 'xml', 'objtex')
OUT = os.path.join(PIPE, 'ml_objtex.otr')
MOD = os.path.join(PIPE, 'ml.otr')

# texture/collision-only XMLs: the File element with its Segment, every <Texture .../> (palettes included) and
# every <Collision .../>
os.makedirs(XML_DIR, exist_ok=True)
for name in os.listdir(XML_DIR):
    os.remove(os.path.join(XML_DIR, name))
for obj in OBJECTS:
    src = open(os.path.join(XML_SRC, obj + '.xml')).read()
    seg = re.search(r'<File Name="\w+"([^>]*)>', src).group(1)
    tex = re.findall(r'^\s*<(?:Texture|Collision) [^>]*/>\s*$', src, flags=re.M)
    open(os.path.join(XML_DIR, obj + '.xml'), 'w').write(
        f'<Root>\n    <!-- generated by inject_obj_textures.py from SoH\'s {obj}.xml: textures only -->\n'
        f'    <File Name="ml_{obj}"{seg}>\n' + '\n'.join('    ' + t.strip() for t in tex) + '\n    </File>\n</Root>\n')

if os.path.exists(OUT):
    os.remove(OUT)
r = subprocess.run([ZAPD, 'ed', '-se', 'OTR', '--otrfile', OUT, '--portVer', '9.1.1',
                    '-i', XML_DIR, '-b', PIPE + '/tml_zapd.z64', '-fl', PIPE + '/filelists',
                    '-o', PIPE + '/out', '-osf', PIPE + '/out', '-gsf', '0', '-rconf', zapd_config()],
                   cwd=ZAPD_CWD, capture_output=True, text=True)
if r.returncode != 0 or not os.path.exists(OUT):
    print(f'object texture extraction FAILED (exit {r.returncode})')
    print(r.stdout[-2000:], r.stderr[-2000:])
    sys.exit(1)

changed = {(obj, name) for obj in OBJECTS for name in ml_changed(obj)}

src, oot = zipfile.ZipFile(OUT), zipfile.ZipFile(OOT_O2R)
stock = set(oot.namelist())
keep, same, missing = {}, 0, []
for n in src.namelist():
    parts = n.split('/')            # [objects/]ml_<object>/<texture>, depending on the XML folder
    if len(parts) < 2 or not parts[-2].startswith('ml_'):
        continue
    van = f'objects/{parts[-2][3:]}/{parts[-1]}'
    if (parts[-2][3:], parts[-1]) not in changed:
        continue                    # ML didn't touch it (any difference from stock is debug-vs-retail)
    mine = src.read(n)
    if mine[4:8] not in (b'XETO', b'LOCO'):   # textures and collisions only (no resource paths inside)
        continue
    if van not in stock:
        missing.append(van)
        continue
    if mine[0x40:] == oot.read(van)[0x40:]:
        same += 1
        continue
    keep[van] = mine

with zipfile.ZipFile(MOD) as old, zipfile.ZipFile(MOD + '.tmp', 'w', zipfile.ZIP_DEFLATED) as z:
    for info in old.infolist():
        if info.filename not in keep:          # REPLACE semantics for the paths we ship
            z.writestr(info, old.read(info.filename))
    for van, data in keep.items():
        z.writestr(van, data)
os.replace(MOD + '.tmp', MOD)
by = {}
for v in keep:
    by[v.split('/')[1]] = by.get(v.split('/')[1], 0) + 1
print(f'object textures: {len(changed)} redrawn by ML, {len(keep)} shipped {by}, {same} already identical to stock'
      + (f', {len(missing)} with no stock path: {missing[:4]}' if missing else ''))
