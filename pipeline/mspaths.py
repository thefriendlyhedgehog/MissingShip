"""Where MissingShip's inputs and neighbouring checkouts live (MS-001).

Every path resolves from this repo's location, so a fresh clone works anywhere. Override any of them with the
matching environment variable (e.g. `MS_DEBUG_ROM=/path/to/rom.z64 python3 tools/dumpactor.py 0x0D`).

    MS_ML_ROM       The Missing Link v2.0 ROM                    default: pipeline/tml_2_0.z64
    MS_DEBUG_ROM    OoT PAL MQ Debug ROM (the diff baseline)     default: roms/oot-mq-debug-pal.z64
    MS_OOT_O2R      oot.o2r generated by SoH                     default: home/oot.o2r
    MS_SHIPWRIGHT   patched Shipwright checkout                  default: ../Shipwright (next to this repo)
    MS_ZAPD         ZAPD built with the engine (patched ZAPDTR)  default: $MS_SHIPWRIGHT/build-ml/ZAPD/ZAPD.out
    MS_ZAPD_CWD     working directory ZAPD runs in               default: $MS_SHIPWRIGHT/soh

One ZAPD and one set of engine tables for every step (MS-009): the engine fork's own. It must be the patched
ZAPDTR (MissingShip-ZAPDTR), whose ZAudio guard ML's audio needs.
"""
import os

def _env(name, default):
    return os.path.abspath(os.path.expanduser(os.environ.get(name, default)))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PIPE = os.path.join(ROOT, 'pipeline')

ML_ROM = _env('MS_ML_ROM', os.path.join(PIPE, 'tml_2_0.z64'))
DEBUG_ROM = _env('MS_DEBUG_ROM', os.path.join(ROOT, 'roms', 'oot-mq-debug-pal.z64'))
OOT_O2R = _env('MS_OOT_O2R', os.path.join(ROOT, 'home', 'oot.o2r'))

SHIPWRIGHT = _env('MS_SHIPWRIGHT', os.path.join(os.path.dirname(ROOT), 'Shipwright'))
SOH = os.path.join(SHIPWRIGHT, 'soh')

ZAPD = _env('MS_ZAPD', os.path.join(SHIPWRIGHT, 'build-ml', 'ZAPD', 'ZAPD.out'))
ZAPD_CWD = _env('MS_ZAPD_CWD', SOH)


def zapd_config():
    """Write the ZAPD config for this checkout (Config_ML.xml with @PIPE@ filled in) and return its path."""
    src = open(os.path.join(PIPE, 'Config_ML.xml')).read().replace('@PIPE@', PIPE)
    out = os.path.join(PIPE, 'out', 'Config_ML.xml')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    if not os.path.exists(out) or open(out).read() != src:
        open(out, 'w').write(src)
    return out


if __name__ == '__main__':
    import sys
    if sys.argv[1:] == ['--zapd-config']:
        print(zapd_config())
    else:   # show the resolved configuration
        for k in ('ROOT', 'ML_ROM', 'DEBUG_ROM', 'OOT_O2R', 'SHIPWRIGHT', 'ZAPD', 'ZAPD_CWD'):
            v = globals()[k]
            print(f'{k:11} {v}' + ('' if os.path.exists(v) else '   (missing)'))
