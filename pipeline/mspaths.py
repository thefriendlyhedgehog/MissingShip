def _env(name, default):
    return os.path.abspath(os.path.expanduser(os.environ.get(name, default)))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PIPE = os.path.join(ROOT, 'pipeline')

ML_ROM = _env('MS_ML_ROM', os.path.join(PIPE, 'tml_2_0.z64'))
DEBUG_ROM = _env('MS_DEBUG_ROM', os.path.join(ROOT, 'roms', 'oot-mq-debug-pal.z64'))
OOT10_ROM = _env('MS_OOT10_ROM', os.path.join(ROOT, 'roms', 'oot-usa10.z64'))
OOT_O2R = _env('MS_OOT_O2R', os.path.join(ROOT, 'home', 'oot.o2r'))

SHIPWRIGHT = _env('MS_SHIPWRIGHT', os.path.join(ROOT, 'engine'))
SOH = os.path.join(SHIPWRIGHT, 'soh')

def _zapd_default():
    # ZAPDTR names its binary ZAPD.out on macOS and Linux, and ZAPD.exe on Windows (under the config directory for
    # a multi-config Visual Studio build). The first one that exists wins; otherwise this OS's usual name.
    d = os.path.join(SHIPWRIGHT, 'build-ml', 'ZAPD')
    names = (['ZAPD.exe', os.path.join('Release', 'ZAPD.exe'), os.path.join('RelWithDebInfo', 'ZAPD.exe'),
              os.path.join('Debug', 'ZAPD.exe')] if os.name == 'nt' else ['ZAPD.out'])
    for n in names:
        if os.path.exists(os.path.join(d, n)):
            return os.path.join(d, n)
    return os.path.join(d, names[0])


ZAPD = _env('MS_ZAPD', _zapd_default())
ZAPD_CWD = _env('MS_ZAPD_CWD', SOH)

